/**
 * 감정·상황 태그
 * ---------------------------------------------------------------
 * 글을 어떤 마음으로 분류할지 정하는 곳. 태그가 곧 별들 사이의 인력입니다.
 * 지금은 키워드 사전으로 뽑습니다. 나중에 임베딩(문장 벡터)으로 바꾸면
 * tagsOf()만 교체하면 되고, 나머지 코드는 그대로입니다.
 */

export const DICTIONARY = [
  [/비|빗방울|장마|우산|소나기|젖/, '비'],
  [/바다|파도|해변|해안|물결|섬|제주/, '바다'],
  [/밤|새벽|자정|불면|잠 못|야식/, '밤'],
  [/혼자|외로|고독|쓸쓸|적막|덩그러니/, '고독'],
  [/피곤|지친|지쳐|한숨|야근|힘들|버겁|번아웃/, '피로'],
  [/회사|출근|퇴근|일|작업|현장|공구|기계|배선|납기/, '일'],
  [/엄마|아빠|가족|동생|누나|형|언니|할머니|할아버지/, '가족'],
  [/고양이|강아지|반려|길냥|새끼|산책/, '동물'],
  [/기쁘|좋았|행복|뿌듯|웃|설레|다행/, '기쁨'],
  [/슬프|눈물|먹먹|울|허전|서럽|그립/, '슬픔'],
]

/** 글에서 마음을 읽어낸다. 아무것도 안 걸리면 '일상'. */
export function tagsOf(text) {
  const found = []
  for (const [pattern, tag] of DICTIONARY) {
    if (pattern.test(text) && !found.includes(tag)) found.push(tag)
  }
  if (found.length === 0) found.push('일상')
  return found.slice(0, 3)
}

/** 두 잔별이 얼마나 닮았는지 (겹치는 태그 수) */
export function similarity(a, b) {
  return a.tags.filter((t) => b.tags.includes(t)).length
}
