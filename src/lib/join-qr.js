/** 둘레의 빈 칸. 이게 없으면 스캐너가 QR 의 경계를 못 찾습니다 */
const QUIET = 4

/** QR 한 칸의 크기를 px 로 — 4px 밑으로 내려가면 잘 안 찍힙니다 */
export const moduleSize = (size) => size / (QR.length + QUIET * 2)

/**
 * QR 을 그립니다.
 *
 * 어두운 바탕에 밝은 QR 을 그리면 안 됩니다 — 반전된 QR 은 못 읽는 스캐너가 많아요.
 * 그래서 밝은 판을 깔고 그 위에 어두운 칸을 찍습니다. 밤하늘에 흰 종이 한 장을
 * 올려둔 셈인데, 읽히지 않는 QR 은 없느니만 못하니 여기선 멋보다 읽힘이 먼저입니다.
 */
export function drawQr(ctx, x, y, size, radius = 16) {
  const m = moduleSize(size)
  ctx.fillStyle = '#EEF0FA'
  ctx.beginPath()
  ctx.roundRect(x, y, size, size, radius)
  ctx.fill()
  ctx.fillStyle = '#070912'
  for (let r = 0; r < QR.length; r++) {
    const row = QR[r]
    for (let c = 0; c < row.length; c++) {
      if (row[c] !== '#') continue
      // 0.5 를 더해 칸 사이에 실금이 보이지 않게 합니다 (소수점 좌표의 안티앨리어싱)
      ctx.fillRect(x + (c + QUIET) * m, y + (r + QUIET) * m, m + 0.5, m + 0.5)
    }
  }
}
